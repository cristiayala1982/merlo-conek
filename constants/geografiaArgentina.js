/**
 * Obtiene los Partidos/Departamentos de una provincia.
 */
export const obtenerPartidosDeProvincia = (provincia) => {
  if (!provincia) return [];
  const lista = PARTIDOS_POR_PROVINCIA[provincia];
  if (lista && lista.length > 0) return lista;
  return [provincia];
};

/**
 * Obtiene las Localidades/Municipios de un Partido.
 */
export const obtenerLocalidadesDePartido = (partido, provincia) => {
  if (!partido) return [];
  if (provincia && LOCALIDADES_POR_PROVINCIA_Y_PARTIDO[provincia]?.[partido]) {
    return LOCALIDADES_POR_PROVINCIA_Y_PARTIDO[provincia][partido];
  }
  return [partido];
};
